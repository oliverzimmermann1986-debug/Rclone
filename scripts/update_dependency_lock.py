"""Refresh a wheel-only runtime hashlock from official PyPI release metadata.

Run this deliberately after reviewing requirement updates. ``--check`` is
offline and checks that the lock still describes the exact runtime pins and
markers. No package is installed, imported, built, or downloaded by this tool.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import tempfile
from typing import Callable
from urllib.parse import quote, urlsplit
from urllib.request import HTTPRedirectHandler, Request, build_opener


PIN = re.compile(
    r"(?P<name>[A-Za-z0-9][A-Za-z0-9_.-]*)(?:\[[A-Za-z0-9_,.-]+\])?"
    r"==(?P<version>[A-Za-z0-9][A-Za-z0-9_.+!-]*)"
    r"(?:\s*;\s*[^\r\n]+)?"
)
HASH = re.compile(r"--hash=sha256:([a-f0-9]{64})")
MAX_METADATA_BYTES = 8 * 1024 * 1024


def normalize_name(value: str) -> str:
    return re.sub(r"[-_.]+", "-", value).lower()


def read_requirements(source: str) -> list[str]:
    pins = []
    names = set()
    for line in source.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        match = PIN.fullmatch(line)
        if not match:
            raise ValueError(
                f"Only exact runtime pins with optional markers are allowed: {line}"
            )
        name = normalize_name(match["name"])
        if name in names:
            raise ValueError(f"Duplicate runtime distribution: {name}")
        names.add(name)
        pins.append(line)
    if not pins:
        raise ValueError("The runtime requirements are empty")
    return pins


def source_digest(pins: list[str]) -> str:
    return hashlib.sha256(("\n".join(pins) + "\n").encode("utf-8")).hexdigest()


class PyPIRedirectsOnly(HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        parsed = urlsplit(newurl)
        if (
            parsed.scheme != "https"
            or parsed.hostname != "pypi.org"
            or parsed.port not in (None, 443)
        ):
            raise ValueError(
                "PyPI redirected release metadata outside its HTTPS origin"
            )
        return super().redirect_request(req, fp, code, msg, headers, newurl)


def fetch_release(name: str, version: str) -> dict:
    url = f"https://pypi.org/pypi/{quote(name, safe='')}/{quote(version, safe='')}/json"
    request = Request(
        url,
        headers={
            "Accept": "application/json",
            "User-Agent": "Sicherpfad-dependency-lock/1",
        },
    )
    with build_opener(PyPIRedirectsOnly()).open(request, timeout=30) as response:
        raw = response.read(MAX_METADATA_BYTES + 1)
    if len(raw) > MAX_METADATA_BYTES:
        raise ValueError(f"PyPI metadata exceeds size limit: {name}=={version}")
    return json.loads(raw)


def wheel_hashes(name: str, version: str, metadata: dict) -> list[str]:
    info = metadata.get("info") or {}
    if (
        normalize_name(str(info.get("name", ""))) != normalize_name(name)
        or str(info.get("version")) != version
    ):
        raise ValueError(
            f"PyPI returned a different distribution or release: {name}=={version}"
        )
    hashes = set()
    for item in metadata.get("urls") or []:
        if item.get("packagetype") != "bdist_wheel" or item.get("yanked"):
            continue
        if not str(item.get("filename", "")).endswith(".whl"):
            raise ValueError(f"Non-wheel file labelled as a wheel: {name}=={version}")
        digest = (item.get("digests") or {}).get("sha256", "")
        if not re.fullmatch(r"[a-f0-9]{64}", digest):
            raise ValueError(f"Missing or invalid wheel SHA-256: {name}=={version}")
        hashes.add(digest)
    if not hashes:
        raise ValueError(f"No non-yanked wheels available: {name}=={version}")
    return sorted(hashes)


def build_lock(
    pins: list[str], fetch: Callable[[str, str], dict] = fetch_release
) -> str:
    lines = [
        "# Generated by scripts/update_dependency_lock.py; review dependency changes before refreshing.",
        "# Official PyPI release metadata; non-yanked wheels only, all published platforms.",
        "# Install with --require-hashes --only-binary=:all:; no source archive hashes are accepted.",
        f"# Runtime pins SHA-256: {source_digest(pins)}",
        "",
    ]
    for pin in pins:
        match = PIN.fullmatch(pin)
        if match is None:
            raise ValueError(f"Invalid pin: {pin}")
        hashes = wheel_hashes(
            match["name"], match["version"], fetch(match["name"], match["version"])
        )
        lines.append(pin + " \\")
        lines.extend(
            "    --hash=sha256:" + digest + (" \\" if index < len(hashes) - 1 else "")
            for index, digest in enumerate(hashes)
        )
        lines.append("")
    return "\n".join(lines)


def validate_lock(pins: list[str], lock: str) -> None:
    marker = f"# Runtime pins SHA-256: {source_digest(pins)}"
    if marker not in lock.splitlines():
        raise ValueError(
            "Runtime requirements changed; review and regenerate requirements.lock"
        )
    logical = []
    pending = ""
    for raw in lock.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        continued = line.endswith("\\")
        pending += line[:-1].strip() + " " if continued else line
        if not continued:
            logical.append(pending.strip())
            pending = ""
    if pending:
        raise ValueError("Unterminated lock continuation")
    actual = []
    for line in logical:
        start = line.find(" --hash=")
        if start < 0:
            raise ValueError("A locked dependency has no wheel hashes")
        pin = line[:start].strip()
        if PIN.fullmatch(pin) is None:
            raise ValueError(
                "A locked dependency has an invalid pin or extra pip option"
            )
        suffix = line[start:].strip()
        hashes = suffix.split()
        if not hashes or any(HASH.fullmatch(value) is None for value in hashes):
            raise ValueError(
                "A locked dependency has an invalid hash or extra pip option"
            )
        actual.append(pin)
    if actual != pins:
        raise ValueError(
            "Locked names, versions, extras, markers or ordering differ from requirements.txt"
        )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--requirements", type=Path, default=Path("requirements.txt"))
    parser.add_argument("--output", type=Path, default=Path("requirements.lock"))
    parser.add_argument(
        "--check",
        action="store_true",
        help="Check pins and lock syntax offline; do not contact PyPI",
    )
    args = parser.parse_args()
    pins = read_requirements(args.requirements.read_text(encoding="utf-8"))
    if args.check:
        validate_lock(pins, args.output.read_text(encoding="utf-8"))
        print(f"Runtime hashlock matches {len(pins)} exact pins")
        return
    lock = build_lock(pins)
    validate_lock(pins, lock)
    # Generate in full before replacing the old lock. Metadata failure preserves it.
    with tempfile.NamedTemporaryFile(
        mode="w", encoding="utf-8", newline="\n", dir=args.output.parent, delete=False
    ) as handle:
        temporary = Path(handle.name)
        handle.write(lock)
    try:
        os.replace(temporary, args.output)
    finally:
        temporary.unlink(missing_ok=True)
    print(f"Updated {args.output}: {len(pins)} distributions, wheels only")


if __name__ == "__main__":
    main()
