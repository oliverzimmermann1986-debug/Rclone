'use strict';

const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { parseHTML } = require('linkedom');

const staticDir = path.resolve(__dirname, '../../app/static');
const workspace = fs.readFileSync(path.join(staticDir, 'workspace.js'), 'utf8');
const watchSources = fs.readdirSync(staticDir).filter((file) => /^app(?:-[\w-]+)?\.js$/.test(file))
  .map((file) => fs.readFileSync(path.join(staticDir, file), 'utf8'));

function compileBindings(html) {
  const { document, window } = parseHTML(html.replace(/\r\n?/g, '\n'));
  window.app = () => ({});
  vm.runInNewContext(workspace, { window, document }, { filename: 'workspace.js' });

  // Alpine evaluates implicit lifecycle hooks, an empty component and default loop keys.
  const expressions = new Set(['', '{}', 'init', 'destroy', 'index']);
  for (const source of [...watchSources, workspace]) {
    for (const [, , expression] of source.matchAll(/\.\$watch\(\s*(['"])([^'"]+)\1\s*,/g)) {
      expressions.add(expression);
    }
  }
  function collect(root) {
    for (const node of root.children) {
      for (const { name, value } of node.attributes) {
        const directive = name.split(/[.:]/, 1)[0];
        if (!name.startsWith('@') && !name.startsWith(':') && !name.startsWith('x-')) continue;
        if (['x-ref', 'x-cloak', 'x-ignore', 'x-teleport'].includes(directive)) continue;
        if (directive === 'x-for') {
          const items = value.match(/([\s\S]*?)\s+(?:in|of)\s+([\s\S]*)/)?.[2].trim();
          if (!items) throw new Error(`Invalid x-for: ${value}`);
          expressions.add(items);
        } else {
          expressions.add(value);
          if (directive === 'x-model' || directive === 'x-modelable') {
            expressions.add(`${value} = __placeholder`);
          }
        }
      }
      collect(node.localName === 'template' ? node.content : node);
    }
  }
  collect(document);

  // Match Alpine 3.14.1's assignment and completion semantics, including event
  // handlers with multiple statements. Only checked-in bindings are compiled.
  const entries = [...expressions].sort().map((expression) => {
    const statement = /^[\s]*if.*\(.*\)/.test(expression.trim()) || /^(let|const)\s/.test(expression.trim());
    const code = !expression.trim() ? 'undefined' : (statement ? `(async () => { ${expression} })()` : expression);
    return `  [${JSON.stringify(expression)}, async function (__self, scope) { with (scope) { __self.result = ${code} }; __self.finished = true; return __self.result; }],`;
  });
  const output = [
    '/* Generated by tests/web/compile-alpine.cjs. Edit the original HTML or workspace.js. */',
    'window.SicherpfadExpressions = new Map([',
    ...entries,
    ']);',
    '',
  ].join('\n');
  new vm.Script(output, { filename: 'alpine-expressions.js' });
  return output;
}

if (require.main === module) {
  const html = fs.readFileSync(path.join(staticDir, 'index.html'), 'utf8');
  const target = path.join(staticDir, 'alpine-expressions.js');
  const output = compileBindings(html);
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(target, 'utf8').replaceAll('\r\n', '\n') !== output) {
      throw new Error('Alpine bindings are stale. Run npm run build:bindings --prefix tests/web.');
    }
  } else {
    fs.writeFileSync(target, output);
  }
}

module.exports = { compileBindings };
